"""Generate ~/.claude/hooks/README.md from what is really wired.

Sources, in the order Claude Code merges them:
  1. ~/.claude/settings.json "hooks"
  2. hooks/hooks.json of every enabled plugin (installPath from
     ~/.claude/plugins/installed_plugins.json)
Hooks listed in env CLAUDE_DISABLED_HOOKS are wired but exit early (off switch).

Usage: python ~/.claude/scripts/hooks-inventory.py [--check]
  --check  exit 1 if README.md is out of date, write nothing.
Stdlib only.
"""
import json
import re
import sys
from pathlib import Path

HOME = Path.home() / ".claude"
README = HOME / "hooks" / "README.md"


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def script_name(command):
    # Last path-looking token that ends in a script, else the first word.
    for tok in reversed(re.split(r"[\s\"']+", command)):
        name = tok.replace("\\", "/").rsplit("/", 1)[-1]
        if name.endswith((".sh", ".py", ".js", ".mjs")) or (tok and "/hooks/" in tok.replace("\\", "/")):
            return name
    return command.split()[0] if command.split() else "?"


def purpose(path):
    # First comment line after the shebang, as the script describes itself.
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()[:15]
    except OSError:
        return ""
    for line in lines:
        s = line.strip()
        if s.startswith("#!") or not s.startswith("#"):
            continue
        text = s.lstrip("#").strip()
        if text and not text.lower().startswith(("shellcheck", "-*-")):
            return text.replace("|", "/")[:110]
    return ""


def rows(hooks, source, script_dir):
    out = []
    for event, groups in hooks.items():
        for g in groups:
            matcher = g.get("matcher", "") or "*"
            for h in g.get("hooks", []):
                cmd = h.get("command", "")
                name = script_name(cmd) if cmd else h.get("type", "?")
                path = script_dir / name
                try:
                    has_switch = "CLAUDE_DISABLED_HOOKS" in path.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    has_switch = False
                out.append((event, matcher, name, source, purpose(path), has_switch))
    return out


def main():
    settings = load(HOME / "settings.json")
    disabled = {x.strip() for x in settings.get("env", {}).get("CLAUDE_DISABLED_HOOKS", "").split(",") if x.strip()}
    table = rows(settings.get("hooks", {}), "settings.json", HOME / "hooks")

    installed = HOME / "plugins" / "installed_plugins.json"
    enabled = {k for k, v in settings.get("enabledPlugins", {}).items() if v}
    if installed.exists():
        for key, entries in load(installed).get("plugins", {}).items():
            if key not in enabled or not entries:
                continue
            base = Path(entries[0].get("installPath", ""))
            hj = base / "hooks" / "hooks.json"
            if hj.exists():
                data = load(hj)
                table += rows(data.get("hooks", data), f"plugin {key.split('@')[0]}", base / "hooks")

    wired = {r[2] for r in table}
    on_disk = sorted(p.name for p in (HOME / "hooks").iterdir() if p.is_file() and p.suffix in (".sh", ".py"))
    unwired = [n for n in on_disk if n not in wired]

    lines = [
        "# `~/.claude/hooks/`: inventory",
        "",
        "Generated by `python ~/.claude/scripts/hooks-inventory.py`. Do not edit by hand: change",
        "`~/.claude/settings.json` (or the plugin) and run the script again.",
        "",
        "Sources: `~/.claude/settings.json` plus `hooks/hooks.json` of each enabled plugin.",
        "A hook named in `CLAUDE_DISABLED_HOOKS` is wired but exits at once (off switch).",
        "",
        "## Wired hooks",
        "",
        "| Event | Matcher | Script | Source | State | Purpose |",
        "|---|---|---|---|---|---|",
    ]
    for event, matcher, name, source, why, has_switch in sorted(table, key=lambda r: (r[0], r[2])):
        stem = name.rsplit(".", 1)[0]
        if stem in disabled and has_switch:
            state = "off (CLAUDE_DISABLED_HOOKS)"
        elif stem in disabled:
            state = "ON: listed as disabled but the script has no off switch"
        else:
            state = "on"
        lines.append(f"| {event} | `{matcher}` | `{name}` | {source} | {state} | {why} |")
    seen = {}
    for event, matcher, name, source, *_ in table:
        seen.setdefault((event, matcher, name), set()).add(source)
    dups = sorted(f"`{n}` ({e}, `{m}`): {', '.join(sorted(s))}" for (e, m, n), s in seen.items() if len(s) > 1)
    lines += ["", f"## Registered twice ({len(dups)})", ""]
    lines += [f"- {d}" for d in dups] or ["- none"]
    lines += ["", f"## On disk but not wired ({len(unwired)})", ""]
    lines += [f"- `{n}`" for n in unwired] or ["- none"]
    text = "\n".join(lines) + "\n"

    current = README.read_text(encoding="utf-8") if README.exists() else ""
    if "--check" in sys.argv:
        if current != text:
            print("hooks/README.md is out of date: run hooks-inventory.py")
            return 1
        print("hooks/README.md: in step")
        return 0
    if current == text:
        print("hooks/README.md: already in step - skipping")
        return 0
    README.write_text(text, encoding="utf-8", newline="\n")
    print(f"hooks/README.md: {len(table)} wired, {len(unwired)} unwired")
    return 0


if __name__ == "__main__":
    sys.exit(main())
