#!/usr/bin/env python3
"""Generate `claude plugin eval` cases from the per-skill evals.json files.

Source of truth stays claude/skills/<skill>/evals/evals.json (skill-creator
format, synced from the live harness). This writes one case per eval to
claude/evals/<skill>--<id>/:

  prompt.md            frontmatter (max_turns, plugins, allowed_tools) + the
                       prompt (prefixed with /<skill> when the skill sets
                       disable-model-invocation, since the model cannot pick it),
                       with fixture files inlined (cases run in a sandbox and
                       cannot read the skill's evals/files/ directory)
  graders/criteria.md  one LLM grader listing the expected output and every
                       assertion

Each case loads claude/skills (`plugins: [../../skills]`), so
`claude plugin eval ./claude --runs 1 --trust-plugin` scores it with and
without the skills and reports the delta.

claude/evals/ is gitignored: regenerate it before each eval run.

Usage: gen-plugin-evals.py
"""
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS = os.path.join(ROOT, "claude", "skills")
OUT = os.path.join(ROOT, "claude", "evals")
DEFAULT_TOOLS = ["Read", "Glob", "Grep", "Skill"]
README = (
    "# Plugin eval cases (generated)\n\n"
    "Generated by `scripts/gen-plugin-evals.py` from "
    "`claude/skills/*/evals/evals.json`. Edit those, not these files.\n\n"
    "Run from the repo root: `claude plugin eval ./claude --runs 1 --trust-plugin`.\n"
)


def assertion_text(a):
    if isinstance(a, dict):
        return a.get("description") or a.get("name") or ""
    return str(a)


def fixture_block(evals_dir, rel):
    path = os.path.join(os.path.dirname(evals_dir), rel)
    if not os.path.isfile(path):
        path = os.path.join(evals_dir, rel)
    if not os.path.isfile(path):
        sys.exit("gen-plugin-evals: fixture %s not found" % path)
    with open(path, encoding="utf-8") as fh:
        body = fh.read().rstrip("\n")
    fence = "````" if "```" in body else "```"
    return "Fixture `%s`:\n\n%s\n%s\n%s\n" % (os.path.basename(rel), fence, body, fence)


def model_invocable(skill):
    with open(os.path.join(SKILLS, skill, "SKILL.md"), encoding="utf-8") as fh:
        head = fh.read().split("\n---", 1)[0]
    return "disable-model-invocation: true" not in head


def write_case(dest, skill, case, evals_dir):
    tools = case.get("allowed_tools") or DEFAULT_TOOLS
    prompt_text = case["prompt"].strip()
    if not model_invocable(skill):
        prompt_text = "/%s %s" % (skill, prompt_text)
    parts = [prompt_text]
    for rel in case.get("files") or []:
        parts.append(fixture_block(evals_dir, rel))
    prompt = "---\nmax_turns: 10\nplugins: [../../skills]\nallowed_tools: [%s]\n---\n\n%s\n" % (
        ", ".join(tools), "\n\n".join(parts))
    lines = ["---", "type: llm", "weight: 1", "---", "",
             "The `%s` skill was expected to handle this prompt." % skill, ""]
    if case.get("expected_output"):
        lines += ["Expected outcome: %s" % case["expected_output"].strip(), ""]
    lines.append("Pass only if every item holds:")
    lines += ["- %s" % assertion_text(a) for a in case.get("assertions") or []]
    os.makedirs(os.path.join(dest, "graders"))
    with open(os.path.join(dest, "prompt.md"), "w", encoding="utf-8") as fh:
        fh.write(prompt)
    with open(os.path.join(dest, "graders", "criteria.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def generate(out):
    count = 0
    for skill in sorted(os.listdir(SKILLS)):
        evals_dir = os.path.join(SKILLS, skill, "evals")
        src = os.path.join(evals_dir, "evals.json")
        if not os.path.isfile(src):
            continue
        with open(src, encoding="utf-8") as fh:
            data = json.load(fh)
        for case in data.get("evals", []):
            write_case(os.path.join(out, "%s--%s" % (skill, case["id"])), skill, case, evals_dir)
            count += 1
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8") as fh:
        fh.write(README)
    return count


def main():
    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(OUT)
    print("gen-plugin-evals: wrote %d cases to claude/evals" % generate(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
